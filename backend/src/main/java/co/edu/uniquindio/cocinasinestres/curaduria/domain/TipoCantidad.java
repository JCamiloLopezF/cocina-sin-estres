package co.edu.uniquindio.cocinasinestres.curaduria.domain;

/**
 * Indica cómo se maneja la cantidad de un producto.
 */
public enum TipoCantidad {

    /**
     * Producto que se maneja por unidades contables.
     */
    CONTABLE,

    /**
     * Producto que se maneja por peso o volumen.
     */
    GRANEL
}
